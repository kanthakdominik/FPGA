"""Czcionka 5×7 (24.03): znaki ' ', '!', '-', '.', ':', '?', '0'–'9', 'A'–'Z'. Generuje funkcję glif()
dla znaki.v / znaki.vhd (35 bitów na znak: wiersz 0 w bitach 34..30, w wierszu bit 4 = lewa kolumna).
Użycie: python3 czcionka.py verilog|vhdl  — wypisuje fragment kodu na standardowe wyjście."""
