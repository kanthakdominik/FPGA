def bity(z):
    w = ZNAKI[z]
    assert len(w) == 7 and all(len(r) == 5 for r in w), z
    return "".join("".join('1' if ch == '#' else '0' for ch in r) for r in w)

def main():
    jezyk = sys.argv[1] if len(sys.argv) > 1 else "verilog"
    for z in sorted(ZNAKI, key=ord):
        if z == ' ':
            continue
        b = bity(z)
        if jezyk == "verilog":
            print(f"            8'h{ord(z):02X}:   glif = 35'b{b};   // {z}")
        else:
            print(f'      when 16#{ord(z):02X}# => return "{b}";   -- {z}')

if __name__ == "__main__":
    main()
