KOD0 = 3431


def temperatura(kod):
    if kod >= TABELA[0][1]:
        return TABELA[0][0]
    if kod <= TABELA[-1][1]:
        return TABELA[-1][0]
    return min(TABELA, key=lambda tk: (abs(tk[1] - kod), tk[0]))[0]


def main():
    slowa = [temperatura(KOD0 + i) & 0xFF for i in range(512)]
    Path(__file__).with_name("tsd_temp.hex").write_text("".join(f"{s:02x}\n" for s in slowa))
    print(f"tsd_temp.hex: 512 słów, kody {KOD0}…{KOD0 + 511}; 25 °C = kod {dict(TABELA)[25]}")


